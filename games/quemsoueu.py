class QuemSouEu(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.partidas = {}
        self.tarefas = {}

    @app_commands.command(
        name="quemsoueu",
        description="Tente descobrir a identidade secreta do bot!"
    )
    @app_commands.guild_only()
    async def quemsoueu(self, interaction: discord.Interaction):
        chave = (interaction.guild_id, interaction.channel_id)

        if chave in self.partidas:
            await interaction.response.send_message(
                "Já existe uma partida de Quem Sou Eu neste canal!",
                ephemeral=True
            )
            return

        try:
            if not IDENTIDADES:
                raise ValueError("A lista IDENTIDADES está vazia.")

            identidade = random.choice(IDENTIDADES)

            # Confere se a identidade possui os campos necessários.
            if not all(campo in identidade for campo in ("nome", "categoria")):
                raise ValueError("Uma identidade está sem nome ou categoria.")

            partida = {
                "identidade": identidade,
                "tentativas": 0,
                "dica_revelada": False
            }

            embed = discord.Embed(
                title="🎭 QUEM SOU EU?",
                description=(
                    "Estou pensando em alguma coisa...\n\n"
                    "Pode ser um personagem, animal, lugar, objeto ou cenário.\n\n"
                    "**Como jogar:**\n"
                    "Envie seu palpite terminando com `?`.\n"
                    "Exemplos: `Leão?` ou `/Homem Aranha?`\n\n"
                    "❌ Errou? Continue tentando!\n"
                    "💡 A cada 5 tentativas erradas, vou revelar uma dica.\n\n"
                    "🏆 Quem acertar primeiro vence!"
                ),
                color=discord.Color.purple()
            )

            embed.set_footer(
                text="A identidade é secreta. Boa sorte!"
            )

            await interaction.response.send_message(embed=embed)

            self.partidas[chave] = partida

            tarefa = asyncio.create_task(
                self.encerrar_por_tempo(
                    chave,
                    partida,
                    interaction.channel
                )
            )

            self.tarefas[chave] = tarefa

            print(
                f"[QUEM SOU EU] Partida iniciada em {chave}",
                flush=True
            )

        except Exception as erro:
            print(
                f"[QUEM SOU EU] Erro ao iniciar partida: {erro}",
                flush=True
            )

            if interaction.response.is_done():
                await interaction.followup.send(
                    "Não consegui iniciar a partida. Verifique o console do bot.",
                    ephemeral=True
                )
            else:
                await interaction.response.send_message(
                    "Não consegui iniciar a partida. Verifique o console do bot.",
                    ephemeral=True
                )

    async def encerrar_por_tempo(self, chave, partida, canal):
        try:
            await asyncio.sleep(300)

            if self.partidas.get(chave) is not partida:
                return

            del self.partidas[chave]
            self.tarefas.pop(chave, None)

            identidade = partida["identidade"]

            embed = discord.Embed(
                title="⌛ Fim de jogo!",
                description=(
                    "Ninguém conseguiu descobrir minha identidade!\n\n"
                    f"**Resposta:** {identidade['nome']}\n"
                    f"**Categoria:** {identidade['categoria'].capitalize()}"
                ),
                color=discord.Color.red()
            )

            await canal.send(embed=embed)

        except asyncio.CancelledError:
            pass

        except discord.HTTPException as erro:
            print(
                f"[QUEM SOU EU] Erro ao encerrar partida: {erro}",
                flush=True
            )

    @commands.Cog.listener()
    async def on_message(self, message):
        if message.author.bot or message.guild is None:
            return

        chave = (message.guild.id, message.channel.id)
        partida = self.partidas.get(chave)

        if partida is None:
            return

        conteudo = message.content.strip()

        # Aceita tanto "Leao?" quanto "/Leao?".
        if not conteudo.endswith("?"):
            return

        palpite = conteudo[:-1].strip()

        if palpite.startswith("/"):
            palpite = palpite[1:].strip()

        if not palpite:
            return

        identidade = partida["identidade"]

        respostas = [
            identidade["nome"],
            *identidade.get("aliases", [])
        ]

        respostas_normalizadas = [
            self.normalizar(resposta)
            for resposta in respostas
        ]

        if self.normalizar(palpite) in respostas_normalizadas:
            del self.partidas[chave]

            tarefa = self.tarefas.pop(chave, None)
            if tarefa:
                tarefa.cancel()

            embed = discord.Embed(
                title="🎉 IDENTIDADE DESCOBERTA!",
                description=(
                    f"🏆 {message.author.mention} acertou!\n\n"
                    f"**Eu era:** {identidade['nome']}\n"
                    f"**Categoria:** {identidade['categoria'].capitalize()}\n"
                    f"**Tentativas:** {partida['tentativas'] + 1}"
                ),
                color=discord.Color.green()
            )

            embed.set_footer(
                text="Parabéns por descobrir minha identidade!"
            )

            await message.channel.send(embed=embed)
            return

        partida["tentativas"] += 1
        tentativas = partida["tentativas"]

        try:
            await message.add_reaction("❌")
        except discord.HTTPException:
            pass

        if tentativas % 5 == 0:
            if not partida["dica_revelada"]:
                partida["dica_revelada"] = True

                await message.channel.send(
                    f"💡 **DICA:** Sou {identidade['categoria']}!"
                )
            else:
                await message.channel.send(
                    f"💡 **DICA:** Minha categoria é "
                    f"{identidade['categoria']}! Continue tentando."
                )

    @staticmethod
    def normalizar(texto):
        texto = unicodedata.normalize("NFKD", texto)

        texto = "".join(
            caractere
            for caractere in texto
            if not unicodedata.combining(caractere)
        )

        texto = texto.casefold()
        texto = re.sub(r"[^a-z0-9 ]", "", texto)
        texto = re.sub(r"\s+", " ", texto)

        return texto.strip()

    async def cog_unload(self):
        for tarefa in self.tarefas.values():
            tarefa.cancel()

        self.tarefas.clear()
        self.partidas.clear()


async def setup(bot):
    await bot.add_cog(QuemSouEu(bot))